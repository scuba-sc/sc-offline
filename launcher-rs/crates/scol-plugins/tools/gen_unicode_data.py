"""Generate src/unicode_data.rs for scol-plugins.

The sco-core plugin zip verifier (Python) uses three pieces of Python's Unicode data:

  * unicodedata.category() in {Cc, Cf, Cs} to refuse control and format characters in paths,
  * str.casefold() to detect case collisions between archive paths,
  * the cp437 codec for ZIP names that do not set the UTF-8 flag.

Rust has no casefold in its standard library. To agree with the Python tool exactly, this script
dumps the Python tables. Run it with the same Python that runs the corpus cross-check:

    python crates/scol-plugins/tools/gen_unicode_data.py > crates/scol-plugins/src/unicode_data.rs

Normalisation (NFC and NFKC) comes from the unicode-normalization crate instead. The unit test
`unicode_tables_match_python_version` and the cross-check script report a Unicode version skew.
"""
import sys
import unicodedata


def ranges(codepoints):
    out = []
    for cp in codepoints:
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def main():
    cats = []
    folds = []
    for cp in range(0x110000):
        ch = chr(cp)
        if unicodedata.category(ch) in ("Cc", "Cf", "Cs"):
            cats.append(cp)
        if 0xD800 <= cp <= 0xDFFF:
            continue  # surrogates cannot occur in a Rust str
        folded = ch.casefold()
        if folded != ch:
            folds.append((cp, folded))
    cp437 = bytes(range(128, 256)).decode("cp437")
    assert len(cp437) == 128
    assert bytes(range(128)).decode("cp437") == bytes(range(128)).decode("ascii")

    w = sys.stdout.write
    w("// SPDX-License-Identifier: GPL-3.0-only\n")
    w("// @generated by tools/gen_unicode_data.py. Do not edit by hand.\n")
    w("//! Unicode tables copied from Python so the Rust verifier agrees with the Python tool.\n\n")
    w("/// Python `unicodedata.unidata_version` at generation time.\n")
    w('pub const PYTHON_UNICODE_VERSION: &str = "%s";\n\n' % unicodedata.unidata_version)
    w("/// Code point ranges (inclusive) whose general category is Cc, Cf or Cs.\n")
    w("pub static CONTROL_FORMAT_RANGES: &[(u32, u32)] = &[\n")
    for lo, hi in ranges(cats):
        w("    (0x%04X, 0x%04X),\n" % (lo, hi))
    w("];\n\n")
    w("/// Full case folding, as `str.casefold()` does it per code point. Sorted by code point.\n")
    w("pub static CASEFOLD: &[(u32, &str)] = &[\n")
    for cp, folded in folds:
        w('    (0x%04X, "%s"),\n' % (cp, "".join("\\u{%X}" % ord(c) for c in folded)))
    w("];\n\n")
    w("/// Python `cp437` decoding of bytes 0x80 to 0xFF.\n")
    w("pub static CP437_HIGH: [char; 128] = [\n")
    for i in range(0, 128, 8):
        w("    " + " ".join("'\\u{%X}'," % ord(c) for c in cp437[i:i + 8]) + "\n")
    w("];\n")


if __name__ == "__main__":
    main()
