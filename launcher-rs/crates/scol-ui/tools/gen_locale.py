"""Generate src/locale_table.rs for scol-ui from the launcher locale sources.

English: launcher/locale_strings.h (SCO_LAUNCHER_MESSAGES) plus locale/extra_en.ini.
Russian: locales/launcher/ru.ini plus locale/extra_ru.ini.
Run: python tools/gen_locale.py --write   (without --write it only checks).
"""
import argparse
import re
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
ROOT = CRATE.parent.parent.parent  # sc-offline repository root
HEADER = ROOT / 'launcher/locale_strings.h'
RU = ROOT / 'locales/launcher/ru.ini'
TARGET = CRATE / 'src/locale_table.rs'

ENTRY = re.compile(r'X\(\w+,\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)')


def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            out.append({'n': '\n', 't': '\t', '\\': '\\', '"': '"'}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def read_ini(path, escapes=False):
    """key = value lines. ru.ini writes one backslash as two; the extra files do not."""
    d = {}
    for line in path.read_text(encoding='utf-8-sig').replace('\r\n', '\n').split('\n'):
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        k, v = line.split('=', 1)
        v = v.strip()
        d[k.strip()] = v.replace('\\\\', '\\') if escapes else v
    return d


def rs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def table(name, d):
    rows = ''.join(f'    ({rs(k)}, {rs(v)}),\n' for k, v in sorted(d.items()))
    return f'pub const {name}: &[(&str, &str)] = &[\n{rows}];\n'


def generate():
    en = {k: unescape(v) for k, v in ENTRY.findall(HEADER.read_text(encoding='utf-8'))}
    if len(en) < 100:
        raise SystemExit('too few English entries parsed from locale_strings.h')
    en.update(read_ini(CRATE / 'locale/extra_en.ini'))
    ru = read_ini(RU, escapes=True)
    ru.update(read_ini(CRATE / 'locale/extra_ru.ini'))
    return ('// SPDX-License-Identifier: GPL-3.0-only\n'
            '// Generated by tools/gen_locale.py from launcher/locale_strings.h, locales/launcher/ru.ini and\n'
            '// locale/extra_*.ini. Do not edit. Sorted by key.\n\n' + table('EN', en) + '\n' + table('RU', ru))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--write', action='store_true')
    a = ap.parse_args()
    text = generate()
    if a.write:
        TARGET.write_bytes(text.encode('utf-8'))
    elif not TARGET.exists() or TARGET.read_text(encoding='utf-8') != text:
        raise SystemExit('locale_table.rs is stale; run python tools/gen_locale.py --write')


if __name__ == '__main__':
    main()
