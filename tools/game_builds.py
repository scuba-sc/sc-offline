"""Generate the launcher's list of game builds from the pinned sco-core.

Reads <core>/include/sc_game_pack.h (the game pack version and the build its signature rows were
verified on) and <core>/docs/game/builds.json (the register of builds the rows were checked
against). Writes:
  launcher-rs/crates/scol-contract/src/game_builds.json

  python tools/game_builds.py --core external/sco-core            write the file
  python tools/game_builds.py --core external/sco-core --check    fail if the file is stale

The launcher uses the file to tell the player whether the installed game build is the one this
release was checked on, an earlier one, or one nobody checked. It never refuses a build. The file
holds public facts only: build numbers, patch names and changelists, as Core's register has them.
"Checked" means a static signature run on that build's executable; nothing here was run in game.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "launcher-rs/crates/scol-contract/src/game_builds.json"
BUILD = re.compile(r"^\d+\.\d+\.\d+\.\d+$")


def macro(header, name):
    m = re.search(r'^#define\s+%s\s+"([^"]*)"' % re.escape(name), header, re.M)
    if not m:
        sys.exit(f"{name} not found in sc_game_pack.h")
    return m.group(1)


def key(build):
    return tuple(int(p) for p in build.split("."))


def generate(core):
    header = (core / "include/sc_game_pack.h").read_text(encoding="utf-8")
    register = json.loads((core / "docs/game/builds.json").read_text(encoding="utf-8"))
    verified = macro(header, "SCO_GAME_PACK_VERIFIED_BUILD")
    builds = []
    for b in register["builds"]:
        if not BUILD.match(b["build"]):
            sys.exit(f"builds.json: not a four-part build: {b['build']!r}")
        builds.append({"build": b["build"], "patch": b["patch"], "changelist": b["changelist"]})
    if not BUILD.match(verified):
        sys.exit(f"sc_game_pack.h: not a four-part build: {verified!r}")
    listed = [b["build"] for b in builds]
    if len(set(listed)) != len(listed):
        sys.exit("builds.json lists a build twice")
    if verified not in listed:
        sys.exit(f"the verified build {verified} is not in Core's register")
    if max(listed, key=key) != verified:
        sys.exit(f"the verified build {verified} is not the newest build in Core's register")
    doc = {
        "about": "Generated by tools/game_builds.py from sco-core include/sc_game_pack.h and "
        "docs/game/builds.json. Do not edit. The builds Core's signature rows were checked "
        "against (static checks, not in-game runs), oldest first, and the one this release's "
        "game pack is verified on.",
        "game_pack": macro(header, "SCO_GAME_PACK_VERSION"),
        "verified_build": verified,
        "builds": sorted(builds, key=lambda b: key(b["build"])),
    }
    return json.dumps(doc, indent=2, ensure_ascii=True) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--core", required=True, type=Path, help="sco-core source directory")
    ap.add_argument("--check", action="store_true", help="fail when the generated file is stale")
    args = ap.parse_args()
    text = generate(args.core)
    if args.check:
        have = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if have != text:
            sys.exit(f"stale generated file: {OUT.relative_to(ROOT)}; run tools/game_builds.py --core <core>")
        print(f"game builds: {OUT.relative_to(ROOT)} is current")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
