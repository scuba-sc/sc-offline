"""Keep the built-in Russian launcher catalogue in sync with its editable source."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'locales/launcher/ru.ini'
TARGET = ROOT / 'launcher/locale_ru_builtin.h'
DELIMITER = 'SCO_RU_LOCALE'


def generate():
    text = SOURCE.read_text(encoding='utf-8-sig').replace('\r\n', '\n')
    if not text.endswith('\n') or ')' + DELIMITER + '"' in text:
        raise ValueError('Russian catalogue needs a final newline and cannot contain the raw-string delimiter')
    return ('// SPDX-License-Identifier: GPL-3.0-only\n'
            '// Generated by tools/generate_launcher_locale.py from locales/launcher/ru.ini.\n'
            '#pragma once\n\nnamespace sco::launcher::locale {\n'
            'inline constexpr const char kBuiltinRussianCatalogue[] = R"' + DELIMITER + '(' + text +
            ')' + DELIMITER + '";\n} // namespace sco::launcher::locale\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='update the generated header')
    args = parser.parse_args()
    expected = generate()
    if args.write:
        TARGET.write_bytes(expected.encode('utf-8'))
    elif not TARGET.exists() or TARGET.read_text(encoding='utf-8') != expected:
        raise SystemExit('Built-in Russian catalogue is stale; run python3 tools/generate_launcher_locale.py --write')


if __name__ == '__main__':
    main()
